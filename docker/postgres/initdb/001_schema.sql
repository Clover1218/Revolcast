-- ============================================================
-- Revolcast · PostgreSQL 初始化脚本（容器首次启动自动执行）
--
-- 执行位置：/docker-entrypoint-initdb.d/001_schema.sql
-- 执行时机：数据卷为空时由 postgres 镜像自动执行，仅执行一次。
--           若需重跑：docker compose down -v（会清空数据）后重新 up。
-- 内容来源：docs/Revolcast_数据库表设计文档_v1.1.md 附录 B.1，
--           并同步了线上库实际存在的两条索引（批次3 变更 + api_secret_hash 唯一索引）。
--
-- 全部语句均带 IF NOT EXISTS，可重复执行（幂等）。
-- ============================================================

SET client_min_messages = warning;

-- 执行顺序已考虑外键依赖：users / game_servers 先行，其余按引用关系排列。

-- ------------------------------------------------------------
-- 1. users：网站账号
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower ON users (lower(username));
-- 可选：仅当产品规定邮箱全局唯一时启用
-- CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (lower(email)) WHERE email IS NOT NULL;

-- ------------------------------------------------------------
-- 2. game_servers：游戏服务器（WS 接入鉴权 + 业务归属）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS game_servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9-]+$'),
    name VARCHAR(128) NOT NULL,
    description TEXT,
    api_secret_hash VARCHAR(255) NOT NULL,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- per-server API Secret 摘要唯一（游戏服务器 WS 鉴权按 hash 反查 server）
CREATE UNIQUE INDEX IF NOT EXISTS ux_game_servers_api_secret_hash ON game_servers (api_secret_hash);

-- ------------------------------------------------------------
-- 3. qq_bindings：QQ ↔ 网站账号
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qq_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    qq_uin BIGINT NOT NULL,
    bot_id VARCHAR(64) NOT NULL,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
    bound_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    unbound_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_qq_bindings_active_qq ON qq_bindings (qq_uin) WHERE status = 1;
CREATE UNIQUE INDEX IF NOT EXISTS ux_qq_bindings_active_user ON qq_bindings (user_id) WHERE status = 1;
CREATE INDEX IF NOT EXISTS ix_qq_bindings_bot_id ON qq_bindings (bot_id);

-- ------------------------------------------------------------
-- 4. qq_bind_codes：QQ 绑定码（TTL 5 分钟）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS qq_bind_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE CHECK (char_length(code) = 8),
    bot_id VARCHAR(64) NOT NULL,
    qq_uin BIGINT NOT NULL,
    trace_id VARCHAR(64),
    status SMALLINT NOT NULL DEFAULT 0 CHECK (status IN (0,1,2,3)),
    expires_at TIMESTAMPTZ NOT NULL,
    used_by_user_id BIGINT REFERENCES users(id),
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_qq_bind_codes_pending_qq ON qq_bind_codes (qq_uin) WHERE status = 0;
CREATE INDEX IF NOT EXISTS ix_qq_bind_codes_pending_lookup ON qq_bind_codes (bot_id, qq_uin, expires_at) WHERE status = 0;

-- ------------------------------------------------------------
-- 5. server_groups：QQ 群 ↔ 游戏服务器路由
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS server_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES game_servers(id),
    bot_id VARCHAR(64) NOT NULL,
    group_id BIGINT NOT NULL,
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_server_groups_active_route ON server_groups (server_id, bot_id, group_id) WHERE status = 1;
CREATE INDEX IF NOT EXISTS ix_server_groups_active_group_route ON server_groups (bot_id, group_id) WHERE status = 1;
CREATE INDEX IF NOT EXISTS ix_server_groups_server_id ON server_groups (server_id);

-- ------------------------------------------------------------
-- 6. game_bind_codes：游戏角色绑定码（TTL 10 分钟）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS game_bind_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL UNIQUE CHECK (char_length(code) = 8),
    server_id BIGINT NOT NULL REFERENCES game_servers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    qq_uin BIGINT,
    trace_id VARCHAR(64),
    status SMALLINT NOT NULL DEFAULT 0 CHECK (status IN (0,1,2,3)),
    game_name VARCHAR(64),
    game_uuid UUID,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- 批次3 变更：待使用槽位（status=0）必须唯一，避免并发发码落下两条待使用记录。
-- 原 ix_game_bind_codes_pending_user（非唯一）已废弃，此处不再创建。
CREATE UNIQUE INDEX IF NOT EXISTS ux_game_bind_codes_pending_user ON game_bind_codes (server_id, user_id) WHERE status = 0;

-- ------------------------------------------------------------
-- 7. server_game_bindings：账号 ↔ 游戏角色
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS server_game_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES game_servers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    game_name VARCHAR(64) NOT NULL,
    game_uuid UUID NOT NULL,
    bind_code_id BIGINT REFERENCES game_bind_codes(id) ON DELETE SET NULL,
    visibility SMALLINT NOT NULL DEFAULT 1 CHECK (visibility IN (0,1)),
    status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
    bound_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    unbound_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_server_game_bindings_active_user ON server_game_bindings (server_id, user_id) WHERE status = 1;
CREATE UNIQUE INDEX IF NOT EXISTS ux_server_game_bindings_active_uuid ON server_game_bindings (server_id, game_uuid) WHERE status = 1;
CREATE UNIQUE INDEX IF NOT EXISTS ux_server_game_bindings_active_name ON server_game_bindings (server_id, lower(game_name)) WHERE status = 1;
CREATE INDEX IF NOT EXISTS ix_server_game_bindings_active_server ON server_game_bindings (server_id) WHERE status = 1;

-- ------------------------------------------------------------
-- 8. server_message_subscriptions：消息订阅
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS server_message_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id BIGINT NOT NULL REFERENCES game_servers(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    qq_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (server_id, user_id)
);

-- ------------------------------------------------------------
-- 9. web_sessions：网站会话（token 只存 SHA-256）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS web_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    device_name VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_web_sessions_user_id ON web_sessions(user_id);

